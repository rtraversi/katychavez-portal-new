// proof-scan-v2-seed.mjs: turn functions/api/proof-scan-profiles/v2-seed.json
// into supabase/migrations/2003_proof_scan_v2_seed.sql.
//
//   node scripts/proof-scan-v2-seed.mjs          write the migration
//   node scripts/proof-scan-v2-seed.mjs --check  exit 1 if the file is stale
//
// The SQL is idempotent: every insert is guarded by WHERE NOT EXISTS, so rerunning
// it never touches a row that is already there. (ON CONFLICT would not do: the
// rule-set freeze triggers from 2002 fire BEFORE the conflict check and would
// refuse a re-insert into a version a stored scan already uses.)
//
// buildSeedSql() is pure so the test suite can check the committed SQL against
// the JSON without touching the filesystem.

export const SEED_JSON_PATH = 'functions/api/proof-scan-profiles/v2-seed.json';
export const SEED_SQL_PATH = 'supabase/migrations/2003_proof_scan_v2_seed.sql';

const lit = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const int = (v) => {
  if (!Number.isInteger(v)) throw new Error(`Expected an integer, got ${v}`);
  return String(v);
};
const bool = (v) => (v ? 'true' : 'false');
const textArray = (a) => (a.length ? `ARRAY[${a.map(lit).join(', ')}]::text[]` : `'{}'::text[]`);

const ruleSetRef = (rs) =>
  `(SELECT id FROM public.proof_scan_rule_sets WHERE case_type = ${lit(rs.case_type)} AND version = ${int(rs.version)})`;

export function buildSeedSql(seed) {
  const out = [];
  out.push(
    '-- Migration 2003: Proof Scan v2 seed (DACA renewal + General)',
    '--',
    '-- GENERATED by scripts/proof-scan-v2-seed.mjs from',
    '-- functions/api/proof-scan-profiles/v2-seed.json. Do not edit by hand: edit the',
    '-- JSON and rerun the script.',
    '--',
    '-- Idempotent. Every insert is guarded by WHERE NOT EXISTS, so a rerun changes',
    '-- nothing that is already there and never trips the 2002 freeze triggers.',
    '-- Depends on 2002.',
    '',
  );

  for (const rs of seed.rule_sets) {
    out.push(`-- ── ${rs.label} v${rs.version}: ${rs.rules.length} checks, ${rs.package_items.length} package items ──`);
    // The first version becomes current only when the case type has none yet.
    out.push(
      'INSERT INTO public.proof_scan_rule_sets (case_type, version, is_current, label, source_note, created_by)',
      `SELECT ${lit(rs.case_type)}, ${int(rs.version)},`,
      `       NOT EXISTS (SELECT 1 FROM public.proof_scan_rule_sets WHERE case_type = ${lit(rs.case_type)} AND is_current),`,
      `       ${lit(rs.label)}, ${lit(rs.source_note)}, NULL`,
      `WHERE NOT EXISTS (SELECT 1 FROM public.proof_scan_rule_sets WHERE case_type = ${lit(rs.case_type)} AND version = ${int(rs.version)});`,
      '',
    );

    rs.package_items.forEach((item, i) => {
      out.push(
        'INSERT INTO public.proof_scan_package_items (rule_set_id, item_id, form, instance, label, pages, kind, sort_order)',
        `SELECT ${ruleSetRef(rs)},`,
        `       ${lit(item.item_id)}, ${lit(item.form)}, ${lit(item.instance)}, ${lit(item.label)}, ${int(item.pages)}, ${lit(item.kind)}, ${int(i + 1)}`,
        `WHERE NOT EXISTS (SELECT 1 FROM public.proof_scan_package_items WHERE rule_set_id = ${ruleSetRef(rs)} AND item_id = ${lit(item.item_id)});`,
      );
    });
    if (rs.package_items.length) out.push('');

    rs.rules.forEach((r, i) => {
      out.push(
        'INSERT INTO public.proof_scan_rules (rule_set_id, rule_id, title, severity, check_kind, form, page, item, expected,',
        '                                     pass_text, note, source_note, applies_to_item_ids, scope, origin, retired, sort_order)',
        `SELECT ${ruleSetRef(rs)},`,
        `       ${lit(r.rule_id)}, ${lit(r.title)}, ${lit(r.severity)}, ${lit(r.check_kind)},`,
        `       ${lit(r.form)}, ${lit(r.page)}, ${lit(r.item)}, ${lit(r.expected)},`,
        `       ${lit(r.pass_text)}, ${lit(r.note)}, ${lit(r.source_note)}, ${textArray(r.applies_to_item_ids)},`,
        `       ${lit(r.scope)}, ${lit(r.origin)}, ${bool(r.retired)}, ${int(i + 1)}`,
        `WHERE NOT EXISTS (SELECT 1 FROM public.proof_scan_rules WHERE rule_set_id = ${ruleSetRef(rs)} AND rule_id = ${lit(r.rule_id)});`,
      );
      for (const stage of seed.stages) {
        const s = r.stages[stage];
        const rulePk = `(SELECT id FROM public.proof_scan_rules WHERE rule_set_id = ${ruleSetRef(rs)} AND rule_id = ${lit(r.rule_id)})`;
        out.push(
          'INSERT INTO public.proof_scan_rule_stage_settings (rule_pk, stage, state, stage_title, stage_pass_text, stage_expected, gentle_if_no)',
          `SELECT ${rulePk},`,
          `       ${lit(stage)}, ${lit(s.state)}, ${lit(s.stage_title)}, ${lit(s.stage_pass_text)}, ${lit(s.stage_expected)}, ${bool(s.gentle_if_no)}`,
          `WHERE NOT EXISTS (SELECT 1 FROM public.proof_scan_rule_stage_settings WHERE rule_pk = ${rulePk} AND stage = ${lit(stage)});`,
        );
      }
      out.push('');
    });
  }

  return out.join('\n');
}

const isMain = typeof process !== 'undefined'
  && Array.isArray(process.argv)
  && /proof-scan-v2-seed\.mjs$/.test(process.argv[1] || '');

if (isMain) {
  const fs = await import('node:fs');
  const path = await import('node:path');
  const { fileURLToPath } = await import('node:url');
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const seed = JSON.parse(fs.readFileSync(path.join(root, SEED_JSON_PATH), 'utf8'));
  const sql = buildSeedSql(seed);
  const target = path.join(root, SEED_SQL_PATH);
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current !== sql) {
      console.error(`${SEED_SQL_PATH} is out of date. Run: node scripts/proof-scan-v2-seed.mjs`);
      process.exit(1);
    }
    console.log(`${SEED_SQL_PATH} is up to date.`);
  } else {
    fs.writeFileSync(target, sql);
    console.log(`Wrote ${SEED_SQL_PATH}`);
  }
}
